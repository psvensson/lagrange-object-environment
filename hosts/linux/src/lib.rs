//! Native Linux host — ADR 0013 / Bead hqt L1 falsification spike.
//!
//! Runs the EXACT checked-in GLB renderer Component core binary
//! (`test/browser/components/glb/glb.component.wasm`, hash-pinned) under
//! Wasmtime with native `wasi:webgpu` + `wasi-gfx:surface` host imports and the
//! Lagrange `lagrange:assets/provider` import — with NO jco, NO JS, NO browser,
//! NO DOM, and NO winit. This proves the ADR 0013 portability contract: the
//! portable artifact is the Component core binary + host-provided WIT imports,
//! not the browser jco glue.
//!
//! Architecture (Option C — headless offscreen):
//!   - REAL `wasi:webgpu` host impl (`wasi_webgpu_wasmtime::add_to_linker`).
//!   - REAL `wasi-gfx:surface/surface` host impl
//!     (`surface_wasmtime::add_surface_to_linker`) with a dummy offscreen
//!     `GfxWindow` (raw handles never used — see below).
//!   - CUSTOM `wasi-gfx:surface/surface-webgpu` host impl (this module's
//!     `OffscreenContext` via a bindgen `with` remap): instead of an on-screen
//!     wgpu surface, `get-current-texture` hands the Component a host-owned
//!     OFFSCREEN texture (`RENDER_ATTACHMENT | COPY_SRC`, Bgra8unorm —
//!     `PREFERRED_CANVAS_FORMAT` on Linux) created on the Component's own
//!     `gpu-device`, and `present()` copies that texture to a readback buffer
//!     and captures the BGRA bytes. This mirrors the browser CI
//!     `TextureRenderTarget` seam exactly: the Component cannot tell which
//!     realization it got.
//!
//! The queue-id seam: `wasi_webgpu_wasmtime`'s `Device.queue` field is
//! `pub(crate)`, so `present()` cannot name the Component device's queue for
//! the readback copy's `queue_submit` — and an encoded-but-UNSUBMITTED command
//! buffer never executes (`buffer_map_async` does NOT run pending command
//! buffers; that earlier assumption was falsified by an all-zeros readback).
//! The resolution: capture the `QueueId` in `configure` via the runtime's
//! public `HostGpuDevice::queue` host method (which pushes the device's
//! `Arc<QueueId>` into our ResourceTable), then in `present()` `queue_submit`
//! the readback copy on that queue before `buffer_map_async` + poll. No fork,
//! no Component change.

