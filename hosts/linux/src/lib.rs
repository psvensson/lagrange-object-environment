/// Host-owned offscreen render target: the WebGPU analogue of the browser
/// host's `TextureRenderTarget`. The texture is created in `configure` on the
/// Component's OWN device (a texture must be device-connected for the
/// Component to render into it). `present()` captures the BGRA frame.
pub struct OffscreenContext {
    /// The Surface this context renders for; its `width()/height()` are read
    /// LIVE each frame (the Component resizes it via request_set_size after
    /// the host sets the view size), so the per-frame color texture always
    /// matches the depth texture the Component rebuilds from the same source.
    surface: Surface,
    /// The Component's device resource rep + its wgpu-core id, captured in
    /// `configure` (both Copy, so present/get_current_texture can submit,
    /// readback and connect_texture without holding a borrow across the
    /// ResourceTable). The rep rebuilds the Resource handle on demand.
    device_rep: Option<u32>,
    device_id: Option<wgpu_core::id::DeviceId>,
    /// The format/usage captured in `configure`; textures are created fresh
    /// per frame in `get_current_texture`.
    format: wgpu_types::TextureFormat,
    usage: wgpu_types::TextureUsages,
    /// THIS frame's texture (created in `get_current_texture`, read in
    /// `present`; the Component destroys it after present, so it is per-frame).
    texture: Option<wgpu_core::id::TextureId>,
    /// Shared with the owning WorkloadState: every `present()` pushes one
    /// captured BGRA frame (padded rows, `bytes_per_row` stride).
    captured: Arc<Mutex<Vec<Vec<u8>>>>,
}

impl OffscreenContext {
    fn width(&self) -> u32 {
        self.surface.width().max(1)
    }
    fn height(&self) -> u32 {
        self.surface.height().max(1)
    }
    fn bytes_per_row_for(width: u32) -> u32 {
        // 256 = COPY_BYTES_PER_ROW_ALIGNMENT (and COPY_BUFFER_ALIGNMENT).
        width.div_ceil(64) * 256
    }
}

/// Ctx view handed to the generated surface-webgpu `add_to_linker`.
struct OffscreenSurfaceWebgpuCtx<'a> {
    table: &'a mut ResourceTable,
    instance: &'a Arc<wgpu_core::global::Global>,
    captured: &'a Arc<Mutex<Vec<Vec<u8>>>>,
    /// Set once the offscreen context is configured (the Component has its
    /// device and is ready to render) — the frame driver's readiness signal.
    ready: &'a Arc<Mutex<bool>>,
    /// The Component device's queue, captured in `configure` via the runtime's
    /// `HostGpuDevice::queue`; read by `present()`. `None` until configured.
    queue_id: &'a Arc<Mutex<Option<wgpu_core::id::QueueId>>>,
}

trait OffscreenSurfaceWebgpuCtxView: Send {
    fn offscreen_surface_webgpu_ctx(&mut self) -> OffscreenSurfaceWebgpuCtx<'_>;
}

