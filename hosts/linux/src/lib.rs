/// A dummy offscreen "window". Only `width`/`height` are ever read: our custom
/// surface-webgpu never creates a wgpu Surface from the raw handles, so the
/// (required) raw-window-handle impls are simply unreachable.
/// Resizable: the Component creates its Surface with an EMPTY CreateDesc
/// (1x1), and the HOST sizes it afterward via `request_set_size` (exactly like
/// the browser adapter's `surface.setSize`). `Surface::width()/height()` read
/// the window live, so it must be mutable.
struct OffscreenWindow {
    size: Mutex<(u32, u32)>,
}

impl raw_window_handle::HasDisplayHandle for OffscreenWindow {
    fn display_handle(
        &self,
    ) -> Result<raw_window_handle::DisplayHandle<'_>, raw_window_handle::HandleError> {
        unreachable!("offscreen host never creates a wgpu surface from raw handles")
    }
}

impl raw_window_handle::HasWindowHandle for OffscreenWindow {
    fn window_handle(
        &self,
    ) -> Result<raw_window_handle::WindowHandle<'_>, raw_window_handle::HandleError> {
        unreachable!("offscreen host never creates a wgpu surface from raw handles")
    }
}

impl GfxWindow for OffscreenWindow {
    fn height(&self) -> u32 {
        self.size.lock().unwrap().1
    }
    fn width(&self) -> u32 {
        self.size.lock().unwrap().0
    }
    fn request_set_size(&self, width: Option<u32>, height: Option<u32>) {
        let mut size = self.size.lock().unwrap();
        if let Some(w) = width {
            size.0 = w;
        }
        if let Some(h) = height {
            size.1 = h;
        }
    }
}

/// Tracks the surfaces created for one workload so the driver can find the
/// Component's surface and send it animation frames.
type CreatedSurfaces = Arc<Mutex<Vec<Surface>>>;

/// No platform requires a main thread here (no winit, no real surface), so
/// "spawn on the main thread" runs the closure in place. `create_surface`
/// records each created Surface so the frame driver can reach it.
pub struct OffscreenSpawner {
    pub created: CreatedSurfaces,
}

impl MainThreadSpawner for OffscreenSpawner {
    fn spawn<F, T>(&self, f: F) -> impl Future<Output = T>
    where
        F: FnOnce() -> T + Send + 'static,
        T: Send + 'static,
    {
        std::future::ready(f())
    }

    fn create_surface(&self, desc: SurfaceDesc) -> Pin<Box<dyn Future<Output = Surface> + Send>> {
        let surface = Surface::new(Box::new(OffscreenWindow {
            size: Mutex::new((desc.width.unwrap_or(1), desc.height.unwrap_or(1))),
        }));
        self.created.lock().unwrap().push(surface.arc_clone());
        Box::pin(std::future::ready(surface))
    }
}

