struct WorkloadState {
    table: ResourceTable,
    instance: Arc<wgpu_core::global::Global>,
    spawner: OffscreenSpawner,
    /// This instance's attach-scoped asset allowlist (per-instance isolation:
    /// instance A's closure contains only A's bytes).
    allowlist: HashMap<String, Vec<u8>>,
    /// Frames captured by `present()` on this instance's offscreen context.
    captured: Arc<Mutex<Vec<Vec<u8>>>>,
    /// Set once the offscreen context is configured (frame-driver readiness).
    ready: Arc<Mutex<bool>>,
    /// What the Component printed (diagnostics).
    prints: Arc<Mutex<Vec<String>>>,
    /// The Component device's queue, captured in `configure`; read by `present()`.
    queue_id: Arc<Mutex<Option<wgpu_core::id::QueueId>>>,
}

impl HasData for WorkloadState {
    type Data<'a> = &'a mut WorkloadState;
}

impl WasiWebGpuCtxView for WorkloadState {
    fn webgpu_ctx(&mut self) -> WasiWebGpuCtx<'_> {
        WasiWebGpuCtx {
            instance: &self.instance,
            table: &mut self.table,
        }
    }
}

impl SurfaceCtxView for WorkloadState {
    type Spawner = OffscreenSpawner;
    fn surface_ctx(&mut self) -> SurfaceCtx<'_, OffscreenSpawner> {
        SurfaceCtx {
            table: &mut self.table,
            main_thread_spawner: &self.spawner,
        }
    }
}

impl OffscreenSurfaceWebgpuCtxView for WorkloadState {
    fn offscreen_surface_webgpu_ctx(&mut self) -> OffscreenSurfaceWebgpuCtx<'_> {
        OffscreenSurfaceWebgpuCtx {
            table: &mut self.table,
            instance: &self.instance,
            captured: &self.captured,
            ready: &self.ready,
            queue_id: &self.queue_id,
        }
    }
}

impl lagrange::assets::provider::Host for WorkloadState {
    fn load(&mut self, name: String) -> Result<Result<Vec<u8>, String>, wasmtime::Error> {
        Ok(match self.allowlist.get(&name) {
            Some(bytes) => Ok(bytes.clone()),
            None => Err(format!("not in allowlist: {name}")),
        })
    }
}

impl GlbRendererImports for WorkloadState {
    fn print(&mut self, s: String) -> wasmtime::Result<()> {
        self.prints.lock().unwrap().push(s.clone());
        log::info!(target: "glb-component", "{s}");
        Ok(())
    }
}

// Registration is per-interface via the marker-struct pattern (the runtime
// crates' design): each interface's generated `add_to_linker::<T, D>` routes
// to a HasData marker D whose `Data<'a>` is that interface's ctx struct, and
// WorkloadState's ctx views produce those ctx structs. The world's unified
// `GlbRenderer::add_to_linker` is NOT usable here because it requires a single
// D::Data that is simultaneously WasiWebGpuCtx + SurfaceCtx +
// OffscreenSurfaceWebgpuCtx (three different structs) — impossible. So we call
// each interface's add_to_linker with its own marker, then register the two
// world-owned imports (print + lagrange:assets/provider) against WorkloadState
// directly.

/// HasData marker for the lagrange:assets/provider + print imports, whose host
/// state is the WorkloadState itself.
struct HasWorkload;

impl HasData for HasWorkload {
    type Data<'a> = &'a mut WorkloadState;
}

