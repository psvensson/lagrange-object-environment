/// Count shaded-mesh pixels in a captured BGRA frame. Browser logic (RGBA):
/// `r > 40 && g > 35 && b < r - 15`. On Linux the frame is BGRA, so byte 0 is
/// B and byte 2 is R — expressed with explicit names so the swap is obvious.
pub fn mesh_pixels(frame: &[u8], width: u32, height: u32, bytes_per_row: u32) -> usize {
    let mut mesh = 0;
    for y in 0..height as usize {
        for x in 0..width as usize {
            let i = y * bytes_per_row as usize + x * 4;
            let b = frame[i] as i32;
            let g = frame[i + 1] as i32;
            let r = frame[i + 2] as i32;
            if r > 40 && g > 35 && b < r - 15 {
                mesh += 1;
            }
        }
    }
    mesh
}

